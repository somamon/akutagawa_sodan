/** システムプロンプトに埋め込む引用集セクションを組み立てる */
export function buildQuotesSection(): string {
  return AKUTAGAWA_QUOTES.map(
    (quote) => `- 「${quote.text}」（『${quote.source}』｜${quote.theme}）`,
  ).join('\n')
}
